function dump(name, texts) {
  const rows = META.map(([id, boosts]) => {
    const text = texts[id].replace(/\\/g, '\\\\').replace(/'/g, "\\'");
    return `  {\n    id: '${id}',\n    boosts: ${boosts},\n    text: '${text}',\n  },`;
  });
  return `/** ${name} mock open notes. Same ids and boosts as English. */\nexport const OPEN_NOTES_${name === 'Japanese' ? 'JA' : 'RU'} = [\n${rows.join('\n')}\n];\n`;
}

