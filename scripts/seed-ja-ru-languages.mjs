function ser(value) {
  return JSON.stringify(value);
}

function build(label, special) {
  const lines = [`/** ${label} language names. */`, 'export const languages = {'];
  for (const lang of enLangs) {
    lines.push(`  ${lang.id}: ${ser(special[lang.id] ?? lang.name)},`);
  }
  lines.push('};', '');
  return `${lines.join('\n')}\n`;
}

