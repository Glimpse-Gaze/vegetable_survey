export function scoreNote(note, net = 0) {
  return (note.boosts ?? 0) + net;
}

export function rankNotes(pool, nets = {}) {
  return [...pool]
    .map((note) => ({
      ...note,
      net: nets[note.id] ?? 0,
      score: scoreNote(note, nets[note.id] ?? 0),
    }))
    .sort(
      (a, b) =>
        b.score - a.score || b.net - a.net || a.id.localeCompare(b.id),
    );
}

export function notePageCount(total, pageSize = NOTE_PAGE_SIZE) {
  return Math.max(1, Math.ceil(Math.max(0, total) / pageSize));
}

export function pageNotes(ranked, pageIndex, pageSize = NOTE_PAGE_SIZE) {
  const pages = notePageCount(ranked.length, pageSize);
  const page = ((pageIndex % pages) + pages) % pages;
  return {
    page,
    pages,
    items: ranked.slice(page * pageSize, page * pageSize + pageSize),
  };
}

export function getNotesSection(category, region) {
  return {
    ...category,
    region,
    notePool: OPEN_NOTES,
    userNoteText: category.userNoteText ?? '',
    responseCount: region.votes,
  };
}
