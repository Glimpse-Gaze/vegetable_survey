export const CONTINENT_IDS = [
  'africa',
  'asia',
  'europe',
  'north_america',
  'oceania',
  'south_america',
];

export const CONTINENTS = [
  { id: 'africa', name: 'Africa' },
  { id: 'asia', name: 'Asia' },
  { id: 'europe', name: 'Europe' },
  { id: 'north_america', name: 'North America' },
  { id: 'oceania', name: 'Oceania' },
  { id: 'south_america', name: 'South America' },
];

const COUNTRY_TO_CONTINENT = Object.fromEntries(
  Object.entries(CONTINENT_COUNTRIES).flatMap(([continentId, countryIds]) =>
    countryIds.map((countryId) => [countryId, continentId]),
  ),
);

export function isContinentId(id) {
  return CONTINENT_IDS.includes(id);
}

export function continentOf(placeId) {
  if (!placeId) return null;
  if (isContinentId(placeId)) return placeId;
  return COUNTRY_TO_CONTINENT[placeId] ?? null;
}

// Country votes count for the country and its continent.
// Continent-only votes count for that continent, never for a country.
export function voteCountsForRegion(placeId, regionId) {
  if (!placeId || placeId === 'prefer_not_to_disclose' || placeId === 'antarctica') {
    return regionId === 'global';
  }
  if (regionId === 'global') return true;
  if (placeId === regionId) return true;
  return isContinentId(regionId) && continentOf(placeId) === regionId;
}
